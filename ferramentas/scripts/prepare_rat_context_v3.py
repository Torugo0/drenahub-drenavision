"""Reproduce reviewed full-frame Hanoi adaptation, retaining scene context.

The entire source clip is a training source, never independent evaluation.
Annotations were reviewed on the five decoded frames, not generated by a model.
The refuse class uses one envelope for the contiguous pile of plastic bottles,
packaging and loose refuse. The roof tile, plant, wall and construction material
are background. The envelope includes small spaces between items; it is not a
segmentation mask or a claim that every enclosed pixel is refuse.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import cv2
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
EXPECTED_VIDEO_SHA256 = (
    "5bd947ce05cc3dab49118747622e29f56d8c7ba1131233fe3ff97cbb02da8030"
)
# Visually reviewed against complete 640 x 480 decoded frames. (class, xyxy)
REVIEWED_BOXES = {
    0: [(2, (290, 164, 390, 237)), (0, (223, 217, 618, 480))],
    2: [(2, (264, 188, 366, 255)), (0, (223, 235, 601, 480))],
    4: [(2, (289, 166, 385, 232)), (0, (224, 215, 640, 480))],
    6: [(2, (220, 188, 316, 255)), (0, (157, 236, 616, 480))],
    10: [(2, (359, 176, 455, 245)), (0, (319, 218, 640, 480))],
}
PILE_POLICY = (
    "One class-0 bounding envelope per contiguous visible refuse pile: bottles, "
    "plastic packaging and loose refuse; small gaps inside the envelope are "
    "allowed. No duplicate individual-item boxes inside the pile. Roof tile, "
    "wall, plant and construction material alone remain background. A pile "
    "does not establish hydraulic obstruction."
)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def prepare(output: Path) -> dict:
    catalog = json.loads((ROOT / "dados/examples/sources.json").read_text("utf-8"))
    source = next(x for x in catalog["items"] if x["id"] == "rato_residuos")
    video = ROOT / "dados/examples" / source["path"]
    if sha256(video) != EXPECTED_VIDEO_SHA256:
        raise ValueError(
            "Source video changed; review timestamps and annotations again"
        )
    (output / "images").mkdir(parents=True, exist_ok=True)
    (output / "labels").mkdir(parents=True, exist_ok=True)
    capture = cv2.VideoCapture(str(video))
    sheet = Image.new("RGB", (1280, len(REVIEWED_BOXES) * 510), "#12213a")
    records = []
    try:
        for row, (second, boxes) in enumerate(REVIEWED_BOXES.items()):
            capture.set(cv2.CAP_PROP_POS_MSEC, second * 1000)
            ok, bgr = capture.read()
            if not ok or bgr.shape[:2] != (480, 640):
                raise RuntimeError(f"Invalid reviewed frame at {second}s")
            image = Image.fromarray(bgr[:, :, ::-1])
            name = f"context_rato_residuos_{second:02d}"
            image_path = output / "images" / f"{name}.jpg"
            label_path = output / "labels" / f"{name}.txt"
            image.save(image_path, quality=95)
            lines = []
            annotated = image.copy()
            draw = ImageDraw.Draw(annotated)
            for class_id, (x1, y1, x2, y2) in boxes:
                if not 0 <= x1 < x2 <= 640 or not 0 <= y1 < y2 <= 480:
                    raise ValueError(f"Invalid box: {name}")
                lines.append(
                    f"{class_id} {(x1 + x2) / 1280:.8f} {(y1 + y2) / 960:.8f} "
                    f"{(x2 - x1) / 640:.8f} {(y2 - y1) / 480:.8f}"
                )
                color = "#a855f7" if class_id == 2 else "#f97316"
                draw.rectangle((x1, y1, x2, y2), outline=color, width=3)
                draw.text(
                    (x1 + 3, max(0, y1 - 16)),
                    "rat" if class_id == 2 else "refuse pile",
                    fill=color,
                    stroke_fill="black",
                    stroke_width=1,
                )
            label_path.write_text("\n".join(lines) + "\n", "utf-8")
            y = row * 510
            sheet.paste(image, (0, y + 30))
            sheet.paste(annotated, (640, y + 30))
            ImageDraw.Draw(sheet).text(
                (8, y + 7),
                f"{second}s ORIGINAL | REVIEWED ANNOTATION (not prediction)",
                fill="white",
            )
            records.append(
                {
                    "id": name,
                    "image": f"images/{name}.jpg",
                    "label": f"labels/{name}.txt",
                    "split": "train",
                    "source_group": "rato_residuos",
                    "source_video": source["path"],
                    "source_video_sha256": EXPECTED_VIDEO_SHA256,
                    "timestamp_seconds": second,
                    "source_url": source["source_url"],
                    "author": source["author"],
                    "license": source["license"],
                    "license_url": source["license_url"],
                    "crop_xyxy_pixels": None,
                    "width": 640,
                    "height": 480,
                    "boxes": [{"class_id": c, "xyxy": list(b)} for c, b in boxes],
                    "annotation_method": "assistant visual review of decoded full frame; no model-generated boxes; not independent human ground truth",
                    "annotation_policy": PILE_POLICY,
                    "image_sha256": sha256(image_path),
                    "label_sha256": sha256(label_path),
                    "evaluation_role": "adaptation_training_full_context",
                }
            )
    finally:
        capture.release()
    sheet.save(output / "review_context.jpg", quality=92)
    manifest = {
        "schema_version": 1,
        "training_only": True,
        "independent_test": False,
        "source_group_policy": "Entire rato_residuos clip is adaptation/training; never split its frames between train/val/test.",
        "annotation_policy": PILE_POLICY,
        "records": records,
    }
    (output / "context_manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), "utf-8"
    )
    sources = {
        "items": [
            {
                "file_name": Path(r["image"]).name,
                "source_url": r["source_url"],
                "source_license": r["license"],
                "source_group": r["source_group"],
                "split": "train",
                "annotation_note": r["annotation_method"] + "; " + PILE_POLICY,
            }
            for r in records
        ]
    }
    (output / "sources.json").write_text(
        json.dumps(sources, ensure_ascii=False, indent=2), "utf-8"
    )
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=ROOT / "dados/interim/rat_context_v3"
    )
    args = parser.parse_args()
    result = prepare(args.output)
    print(f"Prepared {len(result['records'])} reviewed training context frames")
